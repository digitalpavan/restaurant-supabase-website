-- ---------- 3. Row Level Security: public can read the menu ----------
alter table menu_items enable row level security;

drop policy if exists "Public can read menu" on menu_items;
create policy "Public can read menu"
  on menu_items
  for select
  to anon, authenticated
  using (is_available is not false);
-- There is no insert/update/delete policy, so the public API cannot change the menu.
-- Edit the menu in the Supabase Table Editor (it bypasses RLS).

-- ---------- 4. Reservations (used by the website's booking form) ----------
create table if not exists reservations (
  id                bigint generated by default as identity primary key,
  customer_name     text not null,
  phone             text not null,
  reservation_date  date,
  reservation_time  time,
  guests            integer,
  message           text,
  created_at        timestamp with time zone default now()
);

alter table reservations enable row level security;

-- The public may submit a reservation but can never read, change or delete any.
-- View them in the Table Editor.
drop policy if exists "Public can create reservations" on reservations;
create policy "Public can create reservations"
  on reservations
  for insert
  to anon, authenticated
  with check (
    char_length(customer_name) between 1 and 100
    and char_length(phone) between 1 and 30
    and reservation_date >= current_date
    and guests between 1 and 20
    and (message is null or char_length(message) <= 500)
  );
